import requests
from bs4 import BeautifulSoup
import json
import sys

API_KEY = "your-api-key"  # Get at https://shop.pricepulseapi.site
API_URL = "https://pricepulseapi.site/v1/chat/completions"

def call_ai(prompt, model="deepseek-v4-flash", max_tokens=500):
    """Call API Shop with any DeepSeek/Kimi model."""
    response = requests.post(
        API_URL,
        headers={
            "Authorization": f"Bearer {API_KEY}",
            "Content-Type": "application/json",
        },
        json={
            "model": model,
            "messages": [{"role": "user", "content": prompt}],
            "max_tokens": max_tokens,
            "temperature": 0.3,
        },
        timeout=60,
    )
    return response.json()["choices"][0]["message"]["content"]

def scrape_page(url):
    """Scrape a webpage and return clean text."""
    headers = {
        "User-Agent": "Mozilla/5.0 (compatible; APIShopDemo/1.0; +https://shop.pricepulseapi.site)"
    }
    resp = requests.get(url, headers=headers, timeout=15)
    soup = BeautifulSoup(resp.text, "html.parser")

    # Remove scripts and styles
    for tag in soup(["script", "style", "nav", "footer", "header"]):
        tag.decompose()

    text = soup.get_text(separator="\n", strip=True)
    # Clean up whitespace
    lines = [line.strip() for line in text.split("\n") if line.strip()]
    return "\n".join(lines)

