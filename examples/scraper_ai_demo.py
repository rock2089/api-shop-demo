# DEMO 2: Extract structured data (e.g., product listings)
# ============================================================
def extract_structured_data(html_content, schema_description):
    """Use AI to extract structured JSON from scraped HTML."""
    prompt = f"""Extract {schema_description} from this HTML text content.
Return ONLY valid JSON. No explanation, no markdown fences.

Content:
{html_content[:5000]}
"""
    result = call_ai(prompt, model="deepseek-v4-pro", max_tokens=800)
    try:
        return json.loads(result)
    except json.JSONDecodeError:
        # Try to extract JSON from the response
        import re
        match = re.search(r"\[.*\]|\{.*\}", result, re.DOTALL)
        if match:
            return json.loads(match.group())
        return {"raw": result}

