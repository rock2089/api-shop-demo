# DEMO 1: Summarize a webpage
# ============================================================
def summarize_url(url):
    """Scrape and summarize any URL in one call."""
    print(f"Scraping: {url[:60]}...")
    content = scrape_page(url)
    # Limit length to avoid token limits
    content = content[:6000]

    print(f"Analyzing with DeepSeek V4...")
    summary = call_ai(
        f"Summarize this webpage content in 3-5 bullet points. "
        f"Be specific and include key facts/numbers:\n\n{content}",
        model="deepseek-v4-flash",
        max_tokens=300,
    )
    return summary

